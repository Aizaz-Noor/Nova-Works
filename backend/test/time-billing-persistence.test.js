import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openDatabase} from '../src/db/database.js';
import {migratePlatform} from '../src/platform/migrations.js';
import {createPlatformService} from '../src/platform/service.js';
import {createCrmService} from '../src/modules/crm/service.js';
import {createTimesheetService} from '../src/modules/timesheets/service.js';
import {createTaskService} from '../src/modules/projects/taskService.js';
import {createBillingRateService} from '../src/modules/timesheets/billingRates.js';
import {createTimeBillingService} from '../src/modules/invoicing/timeBillingService.js';
import {createInvoiceService} from '../src/modules/invoicing/service.js';
import {invoicePdf} from '../src/modules/invoicing/pdf.js';
import {createReportService} from '../src/modules/reports/service.js';

test('fictional approved-time invoice snapshots survive a disk SQLite reopen and migration',async()=>{
 const dir=mkdtempSync(join(tmpdir(),'nw-time-billing-')),file=join(dir,'fixture.sqlite');let db=openDatabase(file);
 try {
  await migratePlatform(db);const platform=createPlatformService(db);
  const owner=await platform.register({name:'Fictional finance owner',email:'owner@time-persistence.test',password:'FictionalTimePersistence2026!'});
  const company=await platform.createOrganization(owner.id,{name:'Fictional time-billing company'}),u=owner.id,o=company.id;
  const reviewer=await platform.register({name:'Fictional independent reviewer',email:'reviewer@time-persistence.test',password:'FictionalTimePersistence2026!'});
  const invite=await platform.invite(u,o,{email:reviewer.email,role:'ADMIN'});await platform.acceptInvitation(reviewer.id,o,invite.token);
  const worker=await platform.register({name:'Fictional delivery worker',email:'worker@time-persistence.test',password:'FictionalTimePersistence2026!'});
  const workerInvite=await platform.invite(u,o,{email:worker.email,role:'MEMBER'});await platform.acceptInvitation(worker.id,o,workerInvite.token);
  const project=await platform.createProject(u,o,{name:'Fictional persistence project'});
  const customer=await createCrmService(db).create(u,o,{name:'Fictional persistence customer'});
  await createCrmService(db).linkProject(u,o,customer.id,{projectId:project.id});
  const task=await createTaskService(db).create(u,o,{projectId:project.id,title:'Fictional approved delivery task',description:'Persistence fixture task',assigneeId:worker.id,deadline:'2099-12-31',estimatedHours:2});
  const rates=createBillingRateService(db),time=createTimesheetService(db);
  const rate=(await rates.create(u,o,{projectId:project.id,customerId:customer.id,currency:'PKR',hourlyMinor:'10001',requestId:'fictional-time-rate'})).rate;
  let entry=(await time.create(worker.id,o,{requestId:'fictional-approved-90-minutes',projectId:project.id,taskId:task.id,workDate:'2026-10-26',minutes:90,billable:true,description:'Fictional approved delivery work'})).entry;
  entry=await time.submit(worker.id,o,entry.id,{version:entry.version});
  entry=await time.review(reviewer.id,o,entry.id,{version:entry.version,decision:'APPROVE',note:'Fictional independent review'});
  assert.notEqual(worker.id,reviewer.id);assert.equal(entry.status,'APPROVED');
  const billing=createTimeBillingService(db),request={requestId:'fictional-time-invoice',projectId:project.id,customerId:customer.id,rateId:rate.id,rateVersion:rate.version,entryIds:[entry.id]};
  const preview=await billing.preview(u,o,request);assert.equal(preview.minutes,'90');assert.equal(preview.subtotalMinor,'15002');
  let invoice=(await billing.create(u,o,request)).invoice;
  assert.equal(invoice.source_kind,'TIME');assert.equal(invoice.sales_order_id,null);assert.equal(invoice.total_minor,'15002');
  await rates.update(u,o,rate.id,{version:rate.version,hourlyMinor:'25000'});
  invoice=await createInvoiceService(db).issue(u,o,invoice.id,{version:invoice.version});
  assert.equal(invoice.status,'ISSUED');

  await db.close();db=openDatabase(file);await migratePlatform(db);
  const invoices=createInvoiceService(db),saved=await invoices.invoice(u,o,invoice.id);
  assert.equal(saved.source_kind,'TIME');assert.equal(saved.sales_order_id,null);assert.equal(saved.total_minor,'15002');assert.equal(saved.status,'ISSUED');
  assert.equal(saved.customer_id,customer.id);assert.equal(saved.customer_name,'Fictional persistence customer');
  assert.equal(saved.items.length,1);assert.equal(saved.items[0].total_minor,'15002');
  assert.equal(saved.timeAllocations.length,1);
  const allocation=saved.timeAllocations[0];
  assert.equal(allocation.entry_id,entry.id);assert.equal(allocation.project_id,project.id);assert.equal(allocation.customer_id,customer.id);
  assert.equal(allocation.user_id,worker.id);assert.ok(allocation.approval_id);assert.equal(allocation.minutes,90);
  assert.equal(allocation.rate_id,rate.id);assert.equal(allocation.rate_version,rate.version);assert.equal(allocation.hourly_minor,'10001');
  assert.equal(allocation.amount_minor,'15002');assert.equal(allocation.description,'Fictional approved delivery work');assert.equal(allocation.work_date,'2026-10-26');
  const savedEntry=await createTimesheetService(db).entry(worker.id,o,entry.id);
  assert.equal(savedEntry.task_id,task.id);assert.equal(savedEntry.approvals.length,1);assert.equal(savedEntry.approvals[0].id,allocation.approval_id);assert.equal(savedEntry.approvals[0].reviewer_id,reviewer.id);
  const currentRate=(await createBillingRateService(db).list(u,o,{projectId:project.id,customerId:customer.id})).rates[0];
  assert.equal(currentRate.hourly_minor,'25000');assert.equal(currentRate.version,rate.version+1);
  const sameRequest=await createTimeBillingService(db).create(u,o,request);
  assert.equal(sameRequest.invoice.id,invoice.id);assert.equal(sameRequest.replayed,true);
  await assert.rejects(createTimeBillingService(db).create(u,o,{...request,rateVersion:rate.version+1,requestId:'fictional-different-request-same-entry'}),error=>error.code==='TIME_NOT_ELIGIBLE');
  const pdf=await invoicePdf(saved);assert.equal(pdf.subarray(0,5).toString(),'%PDF-');
  const report=await createReportService(db).get(u,o,'financial');
  assert.equal(report.currencies.length,1);
  assert.deepEqual(Object.fromEntries(['currency','count','issued_minor','credited_minor','paid_minor','outstanding_minor'].map(key=>[key,report.currencies[0][key]])),{currency:'PKR',count:'1',issued_minor:'15002',credited_minor:'0',paid_minor:'0',outstanding_minor:'15002'});
 } finally {await db.close();rmSync(dir,{recursive:true,force:true});}
});
