import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openDatabase} from '../src/db/database.js';
import {migratePlatform} from '../src/platform/migrations.js';
import {createPlatformService} from '../src/platform/service.js';
import {createPipelineService} from '../src/modules/pipeline/service.js';
import {createSalesService} from '../src/modules/sales/service.js';
import {createInvoiceService} from '../src/modules/invoicing/service.js';
import {invoicePdf} from '../src/modules/invoicing/pdf.js';
import {createTaskService} from '../src/modules/projects/taskService.js';
import {createTimesheetService} from '../src/modules/timesheets/service.js';
import {createReportService} from '../src/modules/reports/service.js';

// Persistent service integration, not browser or PostgreSQL acceptance.
test('fictional engagement preserves customer/deal/order/project/invoice links and exact collection after reopen',async()=>{
 const dir=mkdtempSync(join(tmpdir(),'nw-engagement-')),file=join(dir,'fixture.sqlite');let db=openDatabase(file);
 try {
  await migratePlatform(db);const platform=createPlatformService(db);
  const owner=await platform.register({name:'Fictional owner',email:'owner@engagement.test',password:'IsolatedEngagement2026!'});
  const company=await platform.createOrganization(owner.id,{name:'Fictional service company'}),u=owner.id,o=company.id;
  const reports=createReportService(db);
  assert.deepEqual((await reports.get(u,o,'financial')).currencies,[]);
  assert.deepEqual((await reports.get(u,o,'sales')).orders,[]);
  assert.deepEqual((await reports.get(u,o,'delivery')).projects,[]);
  const member=await platform.register({name:'Fictional worker',email:'worker@engagement.test',password:'IsolatedEngagement2026!'});
  const invite=await platform.invite(u,o,{email:member.email,role:'MEMBER'});await platform.acceptInvitation(member.id,o,invite.token);
  const p=createPipelineService(db),s=createSalesService(db),i=createInvoiceService(db);
  let lead=await p.createLead(u,o,{name:'Fictional buyer',companyName:'Fictional customer'});
  lead=await p.updateLead(u,o,lead.id,{version:lead.version,status:'QUALIFIED'});
  const converted=await p.convertLead(u,o,lead.id,{version:lead.version});
  assert.equal((await p.convertLead(u,o,lead.id,{version:lead.version})).deal.id,converted.deal.id);
  let deal=await p.updateDeal(u,o,converted.deal.id,{version:converted.deal.version,currency:'PKR',amountMinor:'10000',stage:'PROPOSAL'});
  let quote=await s.create(u,o,{customerId:converted.customer.id,dealId:deal.id,title:'Fictional portal',currency:'PKR',terms:'Fixed scope',items:[{description:'Portal delivery',quantity:1,unitMinor:'10000',taxRateBps:0}]});
  quote=await s.issue(u,o,quote.id,{version:quote.version});
  quote=await s.decide(u,o,quote.id,{version:quote.version,approvalReference:'Fictional acceptance only'},true);
  const {order}=await s.convert(u,o,quote.id,{version:quote.version});
  assert.equal((await s.convert(u,o,quote.id,{version:quote.version})).order.id,order.id);
  deal=await p.updateDeal(u,o,deal.id,{version:deal.version,stage:'WON'});
  const {project}=await p.createProject(u,o,deal.id,{version:deal.version,name:'Fictional portal delivery',deadline:'2099-12-31'});
  const tasks=createTaskService(db),time=createTimesheetService(db);
  let task=await tasks.create(u,o,{projectId:project.id,title:'Implement portal',description:'Fictional fixed-price work',assigneeId:member.id,deadline:'2099-12-01',estimatedHours:2});
  task=await tasks.update(member.id,o,task.id,{status:'IN_PROGRESS',version:task.version});task=await tasks.update(member.id,o,task.id,{status:'DONE',version:task.version});
  let entry=(await time.create(member.id,o,{requestId:'engagement-time',projectId:project.id,taskId:task.id,workDate:'2026-01-10',minutes:90,billable:false,description:'Fixed-price delivery effort'})).entry;
  entry=await time.submit(member.id,o,entry.id,{version:entry.version});
  await assert.rejects(time.review(member.id,o,entry.id,{version:entry.version,decision:'APPROVE'}),error=>error.code==='SELF_APPROVAL');
  entry=await time.review(u,o,entry.id,{version:entry.version,decision:'APPROVE',note:'Fictional review'});
  let invoice=(await i.create(u,o,{salesOrderId:order.id})).invoice;
  invoice=await i.issue(u,o,invoice.id,{version:invoice.version});
  const payment={version:invoice.version,requestId:'engagement-receipt',amountMinor:'2500',currency:'PKR',paidOn:'2026-01-10',reference:'Fictional receipt; no money moved'};
  invoice=(await i.pay(u,o,invoice.id,payment)).invoice;
  assert.equal(invoice.total_minor,'10000');assert.equal(invoice.balanceMinor,'7500');
  assert.equal((await i.pay(u,o,invoice.id,payment)).invoice.balanceMinor,'7500');
  assert.equal((await invoicePdf(invoice)).subarray(0,5).toString(),'%PDF-');
  await assert.rejects(i.invoice(member.id,o,invoice.id),error=>error.code==='ROLE_FORBIDDEN');
  const financial=(await reports.get(u,o,'financial')).currencies;
  assert.equal(financial.length,1);assert.equal(financial[0].currency,'PKR');
  assert.equal(financial[0].issued_minor,'10000');assert.equal(financial[0].paid_minor,'2500');assert.equal(financial[0].outstanding_minor,'7500');
  const salesReport=await reports.get(u,o,'sales');assert.deepEqual(salesReport.orders,[{currency:'PKR',count:'1',amount_minor:'10000'}]);
  assert.equal(salesReport.deals[0].status,'WON');assert.equal(salesReport.deals[0].amount_minor,'10000');
  const delivery=await reports.get(member.id,o,'delivery');assert.deepEqual(delivery.tasks,[{status:'DONE',count:'1'}]);assert.equal(delivery.approvedTime.minutes,'90');
  await assert.rejects(reports.get(member.id,o,'financial'),error=>error.code==='ROLE_FORBIDDEN');
  await db.close();db=openDatabase(file);await migratePlatform(db);
  const saved=await createInvoiceService(db).invoice(u,o,invoice.id);
  assert.equal(saved.balanceMinor,'7500');assert.equal(saved.sales_order_id,order.id);
  assert.equal(db.prepare('SELECT customer_id FROM platform_project_customers WHERE project_id=?').get(project.id).customer_id,converted.customer.id);
  assert.equal(db.prepare('SELECT deal_id FROM platform_deal_projects WHERE project_id=?').get(project.id).deal_id,deal.id);
  assert.equal((await createTaskService(db).list(member.id,o)).tasks.find(row=>row.id===task.id).status,'DONE');
  assert.equal((await createTimesheetService(db).entry(member.id,o,entry.id)).status,'APPROVED');
  assert.deepEqual((await createReportService(db).get(u,o,'financial')).currencies,financial);
 } finally {await db.close();rmSync(dir,{recursive:true,force:true});}
});
